// Зона «зʼєднання лише через withActor» (Task 6, план В2-К1а).
//
// `simplycms/db/client` — гола фабрика пулу. Взяте з неї зʼєднання повертає
// обидва тихі режими відмови, які й будує проти себе весь контракт B5″:
//   • запит без `SET LOCAL ROLE` — під власником таблиць він проходить, і
//     RLS мовчки не застосовується (fail-closed зникає без жодної помилки);
//   • `set_config(…, false)` поза транзакцією — claims переживають COMMIT і
//     дістаються наступному клієнту пулу (витік виміряно негативним
//     контролем гейта RLS, Task 5).
// Обидва не падають — вони просто працюють не так, як здається. Тому єдиний
// легальний вхід — `withActor`, а прямий імпорт фабрики поза текою
// `packages/simplycms/src/db/` є помилкою лінту.
//
// 🔴 Другий, незалежний рубіж: субшляху `./db/client` НЕМАЄ в `exports`-мапі
// пакета — магазин фізично не має до нього шляху. Лінт закриває монорепо, де
// tsconfig-аліас `simplycms/*` резолвить будь-яку теку.
//
// 🔴 Патерн один, бо групи `no-restricted-imports` gitignore-подібні:
// `**/db/client` матчить і bare-субшлях `simplycms/db/client`, і ВСІ відносні
// написання (`../db/client`, `../../src/db/client`) — `**` покриває будь-який
// префікс сегментів. Власні файли теки ходять сюди через `./client`, який під
// патерн не підпадає (немає сегмента `db`), — і саме тому зона скоупиться ще
// й `ignores`, а не покладається на форму специфікатора.

/** Група-заборона для `no-restricted-imports`. */
export const dbClientImportGroup = {
  group: ['**/db/client', '**/db/client.*'],
  message:
    'Пряме зʼєднання з БД заборонене: бери транзакцію через withActor із simplycms/db. Голий пул повертає обидва тихі режими відмови (запит без SET LOCAL ROLE; claims поза транзакцією) — контракт B5″.',
};

/** Файли, які САМІ є фабриками db-рантайму, — зона їх не стосується. */
export const DB_RUNTIME_FILES = ['packages/simplycms/src/db/**'];

/**
 * Глобальний блок зони. Іде ПЕРШИМ у конфігу, бо flat config замінює опції
 * правила цілком: блоки, що теж ставлять `no-restricted-imports` (тір-зони,
 * межа довіри плагінів), доливають цю групу до своїх патернів явно.
 */
export const dbClientZoneConfig = {
  files: ['**/*.{ts,tsx,mts,cts,js,jsx,mjs,cjs}'],
  ignores: DB_RUNTIME_FILES,
  rules: {
    'no-restricted-imports': ['error', { patterns: [dbClientImportGroup] }],
  },
};
