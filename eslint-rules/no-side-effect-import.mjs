// Заборона side-effect-імпорту в пакетах із `"sideEffects": false` (трек T).
//
// 🔴 Що саме тут стережеться. Поле `"sideEffects": false` у маніфесті — це
// обіцянка бандлеру магазину: «жоден модуль цього пакета не робить нічого
// самим фактом імпорту». Отримавши її, бандлер має право ВИКИНУТИ модуль, з
// якого нічого не спожито поіменно. Доки обіцянка правдива, це чистий виграш
// у розмірі бандла. Але side-effect-імпорт (`import './register-x';`,
// `import './styles.css';`), доданий колись усередині пакета, перетворює її
// на брехню — і фіча зникає у ПРОДІ магазину мовчки: збірка зелена, типи
// зелені, тести зелені, бо в монорепо код їде через vite-аліаси на джерела,
// а не через `dist` із маніфестом. До треку T цієї пастки в ядрі не існувало;
// трек її створив, тож трек лишає по собі гард.
//
// 🔴 Чому окреме правило, а не селектор у `no-restricted-syntax`. Зона —
// три пакети цілком, і вона перетинається з ТРЬОМА чинними зонами того ж
// правила: i18n (`I18N_MIGRATED_FILES`), контракт серверного env
// (`SERVER_ENV_FILES`) і межа довіри плагінів
// (`PLUGIN_TRUST_BOUNDARY_FILES`). Flat config ЗАМІНЮЄ опції правила цілком,
// а не доливає, тож спільне імʼя правила мовчки вимкнуло б один із
// детекторів на перетині. Виміряно 2026-09-03: блок
// `no-restricted-syntax` на `packages/simplycms/src/**`, доданий у кінець
// конфігу, ПРИБРАВ i18n-помилку на пробному `<div>Привіт</div>` у
// `cart-ui/`. Той самий висновок уже зафіксовано в конфізі для
// `query-key-from-entity` і `mutation-cache-sync` — окреме імʼя правила
// прибирає перетин повністю.
//
// Пара до цього гарда — асерт наявності самого поля в опублікованому
// tarball-і (`tests/published-exports-parity.test.ts`): гард без поля
// беззмістовний, поле без гарда небезпечне.

/** @type {import('eslint').Rule.RuleModule} */
export default {
  meta: {
    type: 'problem',
    schema: [],
    messages: {
      sideEffectImport:
        'Side-effect-імпорт «{{source}}» у пакеті з "sideEffects": false — ' +
        'бандлер магазину має право викинути цей модуль, і фіча зникне в проді мовчки. ' +
        'Або спожий щось поіменно, або зніми "sideEffects": false з маніфеста ' +
        '(тоді онови tests/published-exports-parity.test.ts).',
    },
  },
  create(context) {
    return {
      // Форма без жодного специфікатора — `import 'x';`. Саме вона і тільки
      // вона є для бандлера «імпортом заради побічного ефекту»: усе інше
      // (`import x from`, `import { y } from`, `import type`) має поіменного
      // споживача, за яким модуль лишається в графі.
      ImportDeclaration(node) {
        if (node.specifiers.length > 0) return;
        // `import type` без специфікаторів синтаксично неможливий, але
        // перевірка дешева й робить намір явним.
        if (node.importKind === 'type') return;
        context.report({
          node,
          messageId: 'sideEffectImport',
          data: { source: node.source.value },
        });
      },
    };
  },
};
