-- ── Основна зона доставки ──────────────────────────────────────────────────
-- 🔴 Інваріант «рівно одна основна зона» (часткові індекс і CHECK у 0001,
-- відкладений тригер у 0004) вимагає, щоб вона існувала з першої секунди:
-- `shipping_rates.zone_id` — NOT NULL, а без основної зони тариф не має до
-- чого прив'язатися. Поки вона основна, адмінка її не видалить (лише замінить основну іншою);
-- після заміни цей рядок — звичайна зона, а інваріантом лишається «рівно одна основна».
-- `on conflict (id)` не арбітрує частковий унікальний індекс `is_default`:
-- другу основну воно б не відсікло. Повторного накату файлу немає — міграції
-- котяться один раз за журналом; `on conflict` лише тримає сід ідемпотентним
-- за власним id.
insert into public.shipping_zones (id, name, is_active, is_default, sort_order)
values ('00000007-0000-4000-8000-000000000001', 'Основна зона', true, true, 0)
on conflict (id) do nothing;
