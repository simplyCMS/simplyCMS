-- ── Покоління кешів читання ────────────────────────────────────────────────
-- Мультимовність М1, Д6: `bumpCacheGeneration` лише ЗБІЛЬШУЄ наявний рядок і
-- відмовляє на незасіяному ключі, тож набір ключів (`CACHE_KEYS` ядра) тримає
