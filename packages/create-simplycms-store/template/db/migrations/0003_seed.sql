-- 0003_seed.sql — довідники ЧИСТОГО магазину (рішення B13).
--
-- 🔴 Це не демо-дані. Тут рівно той мінімум, без якого порожня БД не здатна
-- прийняти першого власника й показати вітрину: статуси замовлень, мова,
-- тип ціни, категорія покупця, дві системні налаштування і рядок активної
-- теми та основна зона доставки. Товари, розділи, банери, точки самовивозу
-- й тарифи доставки — робота адміна, а не міграції.
--
-- Міграції котяться один раз за журналом, повторного накату файлу немає.
-- `on conflict do nothing` по природному унікальному ключу лишається, щоб сід
-- був ідемпотентним за власним ключем (повторний запуск вручну, докат канону).
--
-- 🔴 Е0 (контракт id, В2-К3): id проставлені явно статичними UUID —
-- контракт клієнтської генерації ключів вимагає цього і від сідів. Дані НЕ
-- змінені, лише додано колонку id; FK між рядками сіду й далі резолвиться
-- ПІДЗАПИТОМ за натуральним ключем (`code`), а не константою — на БД, яка
-- вже мала сід, `price_types` несе старий випадковий id, і `on conflict do
-- nothing` не підмінить його на нову константу.

