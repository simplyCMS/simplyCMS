-- 0003_seed.sql — рядки чистого магазину, що не залежать від мови (рішення B13).
--
-- 🔴 Це не демо-дані. Тут лише те, що не має тексту мовою магазину: налаштування
-- залишків, покоління кешів читання й рядок активної теми. Решту мінімуму порожньої БД
-- — мову, статуси замовлень, тип ціни, категорію покупця, профіль магазину й основну
-- зону доставки — вставляє `bootstrapStore` (`simplycms/migrate`, М2б, Р23) на старті
-- бази з основною мовою магазину: тексти довідників беруться з її мовного пакета,
-- тож магазин, що стартує англійською, не отримує українських довідників. Id тих
-- рядків — `SYSTEM_SEED_IDS` (`simplycms/schema`). Товари, розділи, банери, точки
-- самовивозу й тарифи доставки — робота адміна, а не міграції.
--
-- Міграції котяться один раз за журналом, повторного накату файлу немає.
-- `on conflict do nothing` по природному унікальному ключу лишається, щоб сід
-- був ідемпотентним за власним ключем (повторний запуск вручну, докат канону).
--
-- 🔴 Е0 (контракт id, В2-К3): id проставлені явно статичними UUID —
-- контракт клієнтської генерації ключів вимагає цього і від сідів.

-- ── Системні налаштування ──────────────────────────────────────────────────
-- Профіль магазину (`store_profile`) несе назву магазину мовою пакета — його вставляє
-- `bootstrapStore`; тут лише налаштування без тексту.
insert into public.system_settings (id, key, value, description)
values
  (
    '00000005-0000-4000-8000-000000000002',
    'stock_management',
    '{"decrease_on_order": false}'::jsonb,
    'Налаштування управління залишками'
  )
on conflict (key) do nothing;

-- ── Покоління кешів читання ────────────────────────────────────────────────
-- Мультимовність М1, Д6: `bumpCacheGeneration` лише ЗБІЛЬШУЄ наявний рядок і
-- відмовляє на незасіяному ключі, тож набір ключів (`CACHE_KEYS` ядра) тримає
-- цей сід. Ключ — природний PK, не uuid, тому колонки `id` тут немає.
insert into public.cache_generations (key, generation)
values ('store-profile', 0), ('active-theme', 0), ('languages', 0)
on conflict (key) do nothing;

-- ── Активна тема ───────────────────────────────────────────────────────────
-- Рядок у БД потрібен адмінці: вона читає список тем ЛИШЕ звідси, а модуль
-- теми приходить із конфігу магазину. `bootstrapThemes` дописав би його й
-- сам, але тоді чистий магазин до першого відкриття адмінки не мав би
-- активної теми взагалі.
insert into public.themes (id, name, display_name, version, description, author, is_active)
values (
  '00000006-0000-4000-8000-000000000001',
  'default',
  'Default',
  '1.0.0',
  'Базова тема SimplyCMS',
  'SimplyCMS',
  true
)
on conflict (name) do nothing;
