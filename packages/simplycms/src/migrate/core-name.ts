/**
 * Файл міграції ядра відрізняє числовий префікс `NNNN_` (baseline `0000…0005`
 * і далі). Плагіни й власні міграції магазину йдуть таймстампом
 * (`20260814120000_plg_*`: 14 цифр, тож `^\d{4}_` на них не спрацьовує).
 * Окремий модуль без імпортів — його читають і `errors.ts`, і `files.ts`
 * (який сам імпортує `errors.ts`), без циклу.
 */
export function isCoreMigrationName(name: string): boolean {
  return /^\d{4}_/.test(name);
}
