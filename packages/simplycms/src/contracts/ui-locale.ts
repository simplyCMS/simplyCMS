/**
 * Брендований тип «мова ІНТЕРФЕЙСУ» — та, якою говорять кнопки, заголовки, листи й
 * форматування чисел та дат (каталоги ядра, теми, плагіна). Окремий бренд від
 * `ContentLocale` (спека §19.2): це дві осі, і мову контенту (`pl`) не можна подати замість
 * мови інтерфейсу.
 *
 * Тип живе в T0, бо його приймає чиста T1-логіка (`formatPrice` у `simplycms/domain`), а
 * T1 не може імпортувати `simplycms/i18n` (T2). 🔴 Значення створюють ЛИШЕ `resolveUiLocale`
 * і `toUiLocale` (`simplycms/i18n`): код завжди має наявний мовний пакет. Приведення
 * `as UiLocale` деінде заборонене.
 */
export type UiLocale = string & { readonly __axis: 'ui' };
