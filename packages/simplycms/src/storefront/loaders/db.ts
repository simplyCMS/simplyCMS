import { withActor, type ActorDb } from 'simplycms/db';

export type { ActorDb };

/**
 * Транзакція вітрини — єдиний вхід у БД для всіх SSR-лоадерів (В2-К1а).
 *
 * 🔴 Роль завжди `app_user` і завжди БЕЗ `userId`. Вітрина рендериться
 * анонімно: сторінка каталогу однакова для всіх, тож ідентичність тут не
 * потрібна, а `app_admin` для публічного читання зняв би єдиний рубіж, який
 * ще розрізняє покупця й адмінку. Персональні дані (профіль, замовлення)
 * читаються іншими лоадерами й з іншим актором.
 *
 * 🔴 Обгортка приймає ФУНКЦІЮ, а не віддає `db` назовні: усі запити однієї
 * сторінки мають лягти в ОДНУ транзакцію. Інакше кожен лоадер брав би власне
 * зʼєднання пулу — і сторінка збиралася б із кількох різних знімків БД.
 */
export function withStorefrontDb<T>(
  fn: (db: ActorDb) => Promise<T>,
): Promise<T> {
  return withActor({ role: 'app_user' }, (db) => fn(db));
}
