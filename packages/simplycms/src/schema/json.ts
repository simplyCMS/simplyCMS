// Тип значення для jsonb-колонок без власної форми (T1, без рантайм-
// залежностей). Джерело — САМЕ ЦЕЙ файл, а не `simplycms/domain` (тір той
// самий, T1, але `schema` сьогодні не має жодного апстріму — заводити його
// заради одного типу означало б новий тір-звʼязок без потреби) і не
// `drizzle-zod` (той типізує jsonb рекурсивним Json лише в ЗГЕНЕРОВАНІЙ
// Zod-схемі, а не в TS-типі самої Drizzle-колонки — рівно розрив, який тут
// закривається).
//
// 🔴 Колонки з ВІДОМОЮ формою (напр. `images` — масив медіа-референсів)
// типізуються власним конкретним типом (`string[]`), не цим — `JsonValue`
// призначений лише для jsonb-полів без домашньої структури (JSON-LD-подібні
// обʼєкти `returnPolicy`/`shippingDetails`, довільна конфігурація `options`).
export type JsonValue =
  string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };
