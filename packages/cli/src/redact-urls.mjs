// Маскування паролів у рядках підключення: CLI друкує повідомлення ядра й
// драйвера БД, а вони можуть тягнути з собою URL разом із паролем.

/**
 * `scheme://user:pass@host` → `scheme://user:***@host`. Пароль береться до
 * ОСТАННЬОГО `@` авторитету (до першого `/` чи пробілу), бо невкодований `@`
 * у паролі інакше лишив би його хвіст відкритим.
 * @param {string} text
 */
export function redactUrls(text) {
  return String(text).replace(
    /([a-z][a-z0-9+.-]*:\/\/[^\s:@/]*):[^\s/]*@/gi,
    '$1:***@',
  );
}
